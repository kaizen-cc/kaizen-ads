-- The Email Board (Nov 2026): the creative board's way of working, for the email team.
--
-- A ticket is a campaign batch (up to 5 emails or texts) or a flow (up to 6 messages, texts allowed). It moves through
-- Copy for review (the AI writes the copy, the strategist approves) → Ready for design (the client's email designer)
-- → For review (the strategist's final look, after the AI pins its notes on each design) → With client (the portal)
-- → Revisions (each client comment routed to copy or design) → Ready for build (the builder, in Klaviyo, Brevo or
-- Customer.io) → Ready to send (the strategist schedules it or sets the flow live) → live. Texts skip design; a batch
-- of texts only also skips the build. Each message keeps its own copy, design, links with button positions, AI review,
-- client decision, built and live, so a batch can be part approved and part in revisions.
--
-- Tables: email_tickets, email_messages, email_comments (pinned, from the AI, the team or the client, routed to copy or
-- design), email_ticket_events (the history), email_asana_tasks (the Asana email board mirrored while the team moves
-- over, with each task's history and comments), and the email_board view (each ticket's business-hours clock).
-- call_commitments gets email_ticket_numbers: a promise from a call covered by an email ticket.
--
-- Reads: staff who can see the client (the same rule as every email table, the access checked once per query).
-- Writes: only the server (server actions check who's asking, then write with the service role). Client contacts read
-- their own tickets through the server too, after the portal's brand check. Designs live in the existing `creative`
-- storage bucket under email/<ticket>/<message>/. Additive and idempotent: safe to run more than once.

create table if not exists public.email_tickets (
  id                uuid primary key default gen_random_uuid(),
  number            integer generated by default as identity unique,
  client_id         uuid not null references public.clients (id) on delete cascade,
  kind              text not null check (kind in ('batch', 'flow')),
  title             text not null,
  brief             text,                                   -- the AI-written brief: goal, audience, offer, angle
  goal              text,
  trigger           text,                                   -- a flow's trigger (Added to list, Placed order...)
  provider          text not null default 'klaviyo' check (provider in ('klaviyo', 'brevo', 'customerio')),
  stage             text not null default 'copy_review' check (stage in ('copy_review', 'ready_for_design', 'for_review', 'with_client', 'revisions', 'ready_for_build', 'ready_to_send', 'live')),
  priority          text not null default 'normal' check (priority in ('normal', 'high', 'urgent')),
  assignee_id       uuid references public.profiles (id) on delete set null,
  stage_entered_at  timestamptz not null default now(),
  stage_due_at      timestamptz,                            -- the stage's turnaround (business days), or a date someone set
  due_on            date,                                   -- when the whole thing should be sent or live
  client_rounds     integer not null default 0,             -- times the client asked for changes
  copy_status       text not null default 'writing' check (copy_status in ('writing', 'ready', 'failed')),
  suggestion_id     uuid references public.email_suggestions (id) on delete set null,
  asana_gid         text,                                   -- migrated from this Asana task
  created_by        uuid references public.profiles (id) on delete set null,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  live_at           timestamptz,
  deleted_at        timestamptz
);
create index if not exists email_tickets_client on public.email_tickets (client_id, created_at desc);
create index if not exists email_tickets_board on public.email_tickets (stage) where deleted_at is null;
create index if not exists email_tickets_assignee on public.email_tickets (assignee_id) where deleted_at is null;

create table if not exists public.email_messages (
  id               uuid primary key default gen_random_uuid(),
  ticket_id        uuid not null references public.email_tickets (id) on delete cascade,
  client_id        uuid not null references public.clients (id) on delete cascade,
  position         integer not null default 0,
  channel          text not null default 'email' check (channel in ('email', 'sms')),
  name             text not null,                           -- "Black Friday early access", "Welcome 2"
  send_on          date,                                    -- a campaign's send day
  delay_hours      integer,                                 -- a flow step's wait before it (after the trigger or the step before)
  subject          text,
  preheader        text,
  body             text,                                    -- the email's copy (sections in plain text) or the text message
  copy_approved_at timestamptz,
  copy_approved_by uuid references public.profiles (id) on delete set null,
  design_path      text,                                    -- in the creative bucket
  design_mime      text,
  design_version   integer not null default 0,
  design_at        timestamptz,
  links            jsonb not null default '[]',             -- [{label, url, box:{x,y,w,h} in % of the design}]
  ai_review        jsonb,                                   -- {verdict, headline, notes:[{severity, note, box}]}
  ai_review_status text not null default 'none' check (ai_review_status in ('none', 'running', 'done', 'failed')),
  client_status    text check (client_status in ('pending', 'approved', 'changes')),
  client_note      text,
  client_by        text,
  client_at        timestamptz,
  built_at         timestamptz,
  built_by         uuid references public.profiles (id) on delete set null,
  live_at          timestamptz,
  live_by          uuid references public.profiles (id) on delete set null,
  provider_ref     text,                                    -- the campaign or flow in the email platform, when noted
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists email_messages_ticket on public.email_messages (ticket_id, position);
create index if not exists email_messages_client on public.email_messages (client_id);

create table if not exists public.email_comments (
  id            uuid primary key default gen_random_uuid(),
  ticket_id     uuid not null references public.email_tickets (id) on delete cascade,
  message_id    uuid references public.email_messages (id) on delete cascade,
  client_id     uuid not null references public.clients (id) on delete cascade,
  author_kind   text not null check (author_kind in ('ai', 'team', 'client', 'asana')),
  author_id     uuid references public.profiles (id) on delete set null,
  contact_id    uuid references public.contacts (id) on delete set null,
  author_name   text,
  body          text not null,
  box           jsonb,                                   -- a pin on the design: {x, y, w, h} in %
  design_version integer,
  severity      text check (severity in ('fix', 'watch', 'good')),
  route         text check (route in ('copy', 'design')),
  routed_by     text check (routed_by in ('ai', 'team', 'rule')),
  routed_to     uuid references public.profiles (id) on delete set null,
  resolved_at   timestamptz,
  created_at    timestamptz not null default now()
);
create index if not exists email_comments_ticket on public.email_comments (ticket_id, created_at);

