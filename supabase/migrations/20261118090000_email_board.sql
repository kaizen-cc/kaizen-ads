comment on table public.email_comments is 'Notes pinned on email designs: the AI review, the team and the client; client notes routed to copy (strategist) or design (designer)';
comment on table public.email_asana_tasks is 'The Asana email board mirrored while the email team moves to Kaizen (history and comments kept for the migration)';
