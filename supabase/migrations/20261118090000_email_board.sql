-- The board: each ticket with its clock in business minutes (time in the stage, and past its turnaround). Runs with
-- the reader's rights, so it shows only what they may see.
create or replace view public.email_board with (security_invoker = true) as
select
  t.*,
  c.name as client_name,
  c.slug as client_slug,
  p.full_name as assignee_name,
  public.business_minutes_between(t.stage_entered_at, now()) as minutes_in_stage,
  case when t.stage_due_at is not null and t.stage_due_at < now() then public.business_minutes_between(t.stage_due_at, now()) else 0 end as minutes_over
from public.email_tickets t
join public.clients c on c.id = t.client_id
left join public.profiles p on p.id = t.assignee_id
where t.deleted_at is null;
grant select on public.email_board to authenticated;

