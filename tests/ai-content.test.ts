import { describe, expect, it } from "vitest";
import { aiContentAllowed, aiContentRule, aiMediaIn, hasConsentLine, likenessIn, noAiRuleIn } from "@/lib/ai-content";

describe("noAiRuleIn: wording variants that say no to AI content", () => {
  const no = [
    "No AI generated video or AI narration voices, no AI slop",
    "no AI slop",
    "Never use AI-generated images of the food",
    "Client hates AI content",
    "Dislikes AI images that look fake or generic; raised with the email team in Oct 2026",
    "Do not use AI avatars or AI voiceovers.",
    "They don't want anything that looks AI-made",
    "AI voices are off-limits for them",
    "Real footage only: no A.I. video",
    "Real footage only, no AI.",
    "Keep it AI-free",
    "They’re against AI generated content in their ads",
    "Owner said: we don't do synthetic voices or deepfakes",
    "Rejects anything generated by AI",
  ];
  for (const s of no) it(`flags "${s}"`, () => expect(noAiRuleIn(s)).not.toBeNull());

  const fine = [
    "Open to testing AI avatars",
    "AI-generated captions are fine",
    "Loves the AI voiceover ad we ran in October",
    "Uses an AI chatbot on their website",
    "No discounts in ads",
    "Not a fan of stock photos, AI avatars tested well",
    "No problem with AI voices as long as they sound natural",
    "We wrote the copy with AI tools for research",
    "",
  ];
  for (const s of fine) it(`leaves "${s}"`, () => expect(noAiRuleIn(s)).toBeNull());

  it("an avoid item or a don't rule counts when it just names AI media", () => {
    expect(noAiRuleIn("AI voiceovers", true)).not.toBeNull();
    expect(noAiRuleIn("Discount codes", true)).toBeNull();
  });
});

describe("aiContentRule: memory, the Bible's rules log and call notes", () => {
  it("allows AI content when nothing says otherwise", () => {
    expect(aiContentAllowed({ memory: [{ kind: "prefer", body: "Warm, real kitchen footage" }], rules: [], notes: ["Talked about the holiday promo."] })).toBe(true);
    expect(aiContentAllowed({})).toBe(true);
  });

  it("the coffee client's call notes", () => {
    const r = aiContentRule({ notes: ["Went through the new roast launch. They want real baristas on camera. No AI generated video or AI narration voices, no AI slop. Next call in two weeks."] });
    expect(r.allowed).toBe(false);
    expect(r.source).toBe("call");
    expect(r.rule).toMatch(/AI slop/);
  });

  it("an avoid memory item", () => {
    const r = aiContentRule({ memory: [{ kind: "avoid", body: "AI-generated visuals of the dishes" }] });
    expect(r).toMatchObject({ allowed: false, source: "memory" });
  });

  it("a Bible don't rule, and a lifted one opens the door", () => {
    expect(aiContentRule({ rules: [{ rule: "Never use AI images of our food", polarity: "dont", status: "rule" }] })).toMatchObject({ allowed: false, source: "bible" });
    expect(aiContentRule({ rules: [{ rule: "Never use AI images of our food", polarity: "dont", status: "logged" }] }).allowed).toBe(false);
    expect(aiContentAllowed({ rules: [{ rule: "Never use AI images of our food", polarity: "dont", status: "lifted" }], memory: [{ kind: "avoid", body: "AI images" }] })).toBe(true);
  });

  it("ignores rules that aren't about AI media", () => {
    expect(aiContentAllowed({ rules: [{ rule: "Never show prices", polarity: "dont", status: "rule" }], memory: [{ kind: "avoid", body: "Before and after shots" }] })).toBe(true);
  });
});

describe("reading a brief", () => {
  it("finds AI media the brief asks for, not what it rules out", () => {
    expect(aiMediaIn("Hook: an AI avatar of a barista explains the roast")).toMatch(/AI avatar/i);
    expect(aiMediaIn("Use Higgsfield to make a 5s pour shot")).toMatch(/Higgsfield/i);
    expect(aiMediaIn("Voiceover: AI narration in a warm voice")).toMatch(/AI narration/i);
    expect(aiMediaIn("Constraints:\n- No AI video, AI voices or avatars (client rule)\n- Real footage only")).toBeNull();
    expect(aiMediaIn("Don't:\n- AI-generated footage\n- AI voices\n\nKPI: CPA")).toBeNull();
    expect(aiMediaIn("Real baristas, real cafe footage. Add AI-generated captions.")).toBeNull();
  });

  it("finds an altered likeness or voice", () => {
    expect(likenessIn("Rebuild the March testimonial as an AI avatar of the customer")).toMatch(/AI avatar/i);
    expect(likenessIn("Use the review clip with a pitch-shifted voice")).toMatch(/pitch-shifted/i);
    expect(likenessIn("Clone the owner's voice for the VO")).toMatch(/Clone the owner's voice/i);
    expect(likenessIn("Face swap the founder into the kitchen scene")).toMatch(/Face swap/i);
    expect(likenessIn("Real customer testimonial, shot on a phone")).toBeNull();
    expect(likenessIn("Don't alter the customer's voice")).toBeNull();
  });

  it("sees a consent line", () => {
    expect(hasConsentLine("Confirm with client:\n- Get the client's written consent for the customer's likeness/voice")).toBe(true);
    expect(hasConsentLine("Hook: AI avatar")).toBe(false);
  });
});
