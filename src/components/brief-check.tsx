"use client";

import { useEffect, useRef, useState } from "react";
import { answerBriefFact, askClientFact, briefLog, checkBrief, markBriefReviewed, overrideBriefGate, reviseBrief, undoBriefCorrection, type BriefTarget, type CheckResult, type LogEntry, type ReviseTurn } from "@/app/(team)/brief-review-actions";
import { GATE_LABEL, STATUS_LABEL, stampLine, type BriefStatus, type GateKey } from "@/lib/brief-gate";
import { applyTextFix, type LintFix, type LintIssue } from "@/lib/brief-lint";
import type { BriefState, FieldDiff } from "@/lib/brief-patch";

// Under every brief before (and after) it goes to the maker: where it stands in one word (Needs client input, Waiting
// on assets, Fix contradictions, Ready, Reviewed), the facts only the client knows with a place to answer them or ask
// the client, the assets with who to chase and the date risk, the contradictions with one-click fixes, a lead's "send
// anyway" with a reason, and the revise chat: "Tell me what to change", each correction shown as what changed, with
// undo. "Mark reviewed" stamps it "Generated by Kaizen Ads · reviewed by <name>". Used in Ready to send (a draft: its
// changes go to the form) and on the ticket (its changes are saved on the ticket).

type Change = { brief: string; title?: string; angle?: string; audience?: string; sizes?: string[] };
type Turn = { role: "user" | "ai"; text: string; diff?: FieldDiff[]; correctionId?: string | null; undone?: boolean };

const TONE: Record<BriefStatus, string> = {
  needs_client_input: "border-warn/50 bg-warn-soft text-warn",
  waiting_on_assets: "border-warn/50 bg-warn-soft text-warn",
  has_conflicts: "border-bad/40 bg-bad-soft text-bad",
  ready: "border-ok/40 bg-ok-soft text-ok",
  reviewed: "border-ok/40 bg-ok-soft text-ok",
};
const ASSET_TONE: Record<string, string> = { have: "text-ok", need: "text-warn", shoot: "text-warn", missing: "text-bad", unreachable: "text-bad" };
const ASSET_WORD: Record<string, string> = { have: "Have", need: "Need", shoot: "Client to shoot", missing: "Missing", unreachable: "Doesn't open" };

const fromState = (s: BriefState, brief: string): Change => ({ brief, title: s.title, angle: s.angle, audience: s.audience, sizes: s.sizes });

export function BriefCheck({ target, signature, brief, onChange, demo = false }: {
  target: BriefTarget;
  /** Changes whenever the brief does (its text, sizes, title): the check runs again, a moment after typing stops */
  signature: string;
  brief: string;
  /** A change made here (a fix, an answer, a correction, undo) */
  onChange: (c: Change) => void;
  demo?: boolean;
}) {
  const [res, setRes] = useState<CheckResult | null>(null);
  const [checking, setChecking] = useState(false);
  const [ai, setAi] = useState<"idle" | "running">("idle");
  const [turns, setTurns] = useState<Turn[]>([]);
  const [say, setSay] = useState("");
  const [busy, setBusy] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [answers, setAnswers] = useState<Record<string, string>>({});
  const [asked, setAsked] = useState<Record<string, boolean>>({});
  const [overriding, setOverriding] = useState(false);
  const [reason, setReason] = useState("");
  const [log, setLog] = useState<LogEntry[]>([]);
  const targetRef = useRef(target);
  useEffect(() => {
    targetRef.current = target;
  });
  const listRef = useRef<HTMLDivElement>(null);

  const run = (withAi = false) => {
    if (demo) return;
    if (withAi) setAi("running");
    else setChecking(true);
    checkBrief(targetRef.current, withAi)
      .then((r) => setRes((was) => (r.ok && !withAi && was?.ok && was.ai ? { ...r, ai: was.ai } : r)))
      .finally(() => {
        setChecking(false);
        setAi("idle");
      });
  };

  // Checked again a moment after the brief stops changing
  useEffect(() => {
    if (demo || !brief.trim()) return;
    const t = setTimeout(() => run(false), 900);
    return () => clearTimeout(t);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [signature, demo]);

  // A ticket's history of corrections, reviews and overrides
  useEffect(() => {
    if (demo || target.kind !== "ticket") return;
    briefLog(target).then(setLog);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [demo, target.kind === "ticket" ? target.requestId : null]);

  const ok = res?.ok ? res : null;
  const c = ok?.check ?? null;
  const aiIssues = ok?.ai ?? [];
  const hard = [...(c?.hard ?? []), ...aiIssues.filter((x) => x.severity === "hard")];
  const soft = [...(c?.soft ?? []), ...aiIssues.filter((x) => x.severity === "soft")];
  const status: BriefStatus | null = c ? (c.status === "ready" && aiIssues.some((x) => x.severity === "hard") ? "has_conflicts" : c.status) : null;

  const send = async (text: string) => {
    const msg = text.trim();
    if (!msg || busy) return;
    setError(null);
    setBusy("revise");
    const history: ReviseTurn[] = turns.map((t) => ({ role: t.role, text: t.text }));
    setTurns((t) => [...t, { role: "user", text: msg }]);
    setSay("");
    requestAnimationFrame(() => listRef.current?.scrollTo({ top: listRef.current.scrollHeight, behavior: "smooth" }));
    const r = await reviseBrief(targetRef.current, msg, history);
    setBusy(null);
    if (!r.ok) {
      setTurns((t) => [...t, { role: "ai", text: r.error }]);
      return;
    }
    setTurns((t) => [...t, { role: "ai", text: r.reply + (r.refused.length ? ` (Not changed, not yours to change: ${[...new Set(r.refused)].join(", ")}.)` : ""), diff: r.diff, correctionId: r.correctionId }]);
    if (r.diff.length) onChange(fromState(r.state, r.brief));
    requestAnimationFrame(() => listRef.current?.scrollTo({ top: listRef.current.scrollHeight, behavior: "smooth" }));
  };

  const undo = async (i: number, id: string) => {
    setBusy(`undo-${i}`);
    const r = await undoBriefCorrection(id);
    setBusy(null);
    if (!r.ok) return setError(r.error);
    setTurns((t) => t.map((x, j) => (j === i ? { ...x, undone: true } : x)));
    onChange(fromState(r.state, r.brief));
  };

  const fix = (f: LintFix) => {
    if (f.kind === "ai") return void send(f.instruction);
    if (target.kind === "ticket") return void send(f.kind === "sizes" ? `Make the sizes ${f.sizes.map((s) => s.replace("x", ":")).join(" and ")} only, and make every line agree.` : `Change "${f.from}" to "${f.to}".`);
    if (f.kind === "sizes") onChange({ brief, sizes: f.sizes });
    else onChange({ brief: applyTextFix(brief, f.from, f.to) });
  };

  const answer = async (q: string) => {
    const a = (answers[q] ?? "").trim();
    if (!a) return;
    setBusy(`answer-${q}`);
    const r = await answerBriefFact(targetRef.current, q, a);
    setBusy(null);
    if (!r.ok) return setError(r.error);
    setAnswers((x) => ({ ...x, [q]: "" }));
    onChange({ brief: r.brief });
  };

  const askClient = async (q: string) => {
    setBusy(`ask-${q}`);
    const r = await askClientFact(targetRef.current, q);
    setBusy(null);
    if (!r.ok) return setError(r.error);
    setAsked((x) => ({ ...x, [q]: true }));
  };

  const review = async () => {
    setBusy("review");
    setError(null);
    const r = await markBriefReviewed(targetRef.current);
    setBusy(null);
    if (!r.ok) return setError(r.error);
    run(false);
  };

  const override = async () => {
    if (!c) return;
    setBusy("override");
    setError(null);
    const r = await overrideBriefGate(targetRef.current, c.blocking as GateKey[], reason);
    setBusy(null);
    if (!r.ok) return setError(r.error);
    setOverriding(false);
    setReason("");
    run(false);
  };

  if (!brief.trim()) return null;

  return (
    <section aria-label="Before it goes to the maker" className="grid min-w-0 gap-4 rounded-[22px] border border-line bg-surface p-4 md:p-5">
      {/* Where it stands */}
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="flex min-w-0 flex-wrap items-center gap-2">
          {status ? (
            <span className={`inline-flex min-h-8 items-center gap-2 rounded-full border px-3 text-[13px] font-medium ${TONE[status]}`} role="status">
              <span aria-hidden className="h-1.5 w-1.5 rounded-full bg-current" />
              {STATUS_LABEL[status]}
            </span>
          ) : (
            <span className="text-[13px] text-faint">{demo ? "Checks run on the live app" : "Checking the brief…"}</span>
          )}
          {checking && status && <span className="text-[12px] text-faint">Checking…</span>}
          {c?.overridden.length ? <span className="text-[12px] text-muted">Sent on by {c.override?.by}: {c.override?.reason}</span> : null}
        </div>
        {!demo && (
          <button type="button" onClick={() => run(true)} disabled={ai === "running"} className="min-h-11 rounded-full border border-line px-4 text-[13px] text-muted hover:border-faint hover:text-fg disabled:opacity-60 md:min-h-9">
            {ai === "running" ? "Reading it for contradictions…" : "Check for contradictions"}
          </button>
        )}
      </div>
      {c?.stamp && <p className="text-[12.5px] text-ok">{stampLine(c.stamp)}</p>}

      {/* Facts only the client knows */}
      {c && c.openFacts.length > 0 && (
        <div className="grid gap-3 rounded-[16px] border border-warn/40 bg-warn-soft/40 p-3.5">
          <div className="grid gap-0.5">
            <p className="text-[11px] font-semibold uppercase tracking-[0.16em] text-warn">Confirm with client</p>
            <p className="text-[12.5px] leading-snug text-muted">The idea hangs on these. Never made up: answer if you know, or ask the client (it goes to them as a Brand Bible question).</p>
          </div>
          {c.openFacts.map((f) => (
            <div key={f.question} className="grid gap-2">
              <p className="text-[14px] font-medium leading-snug">{f.question}</p>
              {ok?.canEdit && (
                <div className="flex flex-col gap-2 sm:flex-row">
                  <input
                    value={answers[f.question] ?? ""}
                    onChange={(e) => setAnswers((x) => ({ ...x, [f.question]: e.target.value }))}
                    onKeyDown={(e) => e.key === "Enter" && answer(f.question)}
                    placeholder="The answer, if you know it"
                    className="h-11 min-w-0 flex-1 rounded-[12px] border border-line bg-bg/60 px-3.5 text-[16px] outline-none placeholder:text-faint focus:border-brand/60 md:text-[14px]"
                  />
                  <div className="flex gap-2">
                    <button type="button" onClick={() => answer(f.question)} disabled={!answers[f.question]?.trim() || Boolean(busy)} className="min-h-11 flex-1 rounded-full bg-fg px-4 text-[13px] font-medium text-bg disabled:opacity-50 sm:flex-none">
                      {busy === `answer-${f.question}` ? "Saving…" : "Save answer"}
                    </button>
                    <button type="button" onClick={() => askClient(f.question)} disabled={asked[f.question] || Boolean(busy)} className="min-h-11 flex-1 rounded-full border border-line px-4 text-[13px] text-muted hover:border-faint hover:text-fg disabled:opacity-60 sm:flex-none">
                      {asked[f.question] ? "Asked" : busy === `ask-${f.question}` ? "Asking…" : "Ask the client"}
                    </button>
                  </div>
                </div>
              )}
            </div>
          ))}
        </div>
      )}

      {/* Assets */}
      {c?.assets && c.assets.items.length > 0 && (
        <div className="grid gap-2">
          <p className="text-[11px] font-semibold uppercase tracking-[0.16em] text-faint">Assets</p>
          <ul className="grid gap-1.5">
            {c.assets.items.map((a, i) => (
              <li key={`${a.label}-${i}`} className="flex min-w-0 items-start gap-2.5 text-[14px] leading-snug">
                <span className={`mt-0.5 shrink-0 text-[11.5px] font-semibold uppercase tracking-[0.08em] ${ASSET_TONE[a.status]}`}>{ASSET_WORD[a.status]}</span>
                <span className="min-w-0 break-words text-fg/90">
                  {a.label}
                  {a.note && <span className="block text-[12px] text-faint">{a.note}</span>}
                </span>
              </li>
            ))}
          </ul>
          {c.assets.state === "waiting" && (
            <p className="text-[12.5px] text-muted">
              Chase {c.assets.chase}.{c.assets.driveMatches > 0 ? ` ${c.assets.driveMatches} file${c.assets.driveMatches === 1 ? "" : "s"} on their Drive look like this concept's: check them first.` : ""}
            </p>
          )}
          {c.assets.risk && <p className="rounded-[12px] bg-bad-soft px-3 py-2 text-[13px] font-medium text-bad">{c.assets.risk}</p>}
        </div>
      )}

      {/* Contradictions */}
      {(hard.length > 0 || soft.length > 0) && (
        <div className="grid gap-2">
          <p className="text-[11px] font-semibold uppercase tracking-[0.16em] text-faint">{hard.length ? "Contradictions" : "Worth a look"}</p>
          {[...hard, ...soft].map((x: LintIssue) => (
            <div key={x.id} className={`grid gap-2 rounded-[14px] border px-3.5 py-3 ${x.severity === "hard" ? "border-bad/40 bg-bad-soft/40" : "border-line bg-bg/60"}`}>
              <p className="text-[14px] leading-snug">{x.message}</p>
              {ok?.canEdit && !ok.copyOnly && x.fixes.length > 0 && (
                <div className="flex flex-wrap gap-2">
                  {x.fixes.map((f) => (
                    <button key={f.label} type="button" onClick={() => fix(f)} disabled={Boolean(busy)} className="min-h-11 rounded-full border border-line bg-surface px-3.5 text-[13px] hover:border-faint disabled:opacity-60 md:min-h-9">
                      {f.label}
                    </button>
                  ))}
                </div>
              )}
            </div>
          ))}
        </div>
      )}

      {/* A lead sends it on anyway */}
      {c && c.blocking.length > 0 && ok?.canOverride && (
        <div className="grid gap-2">
          {!overriding ? (
            <button type="button" onClick={() => setOverriding(true)} className="min-h-11 justify-self-start rounded-full border border-line px-4 text-[13px] text-muted hover:border-faint hover:text-fg md:min-h-9">
              Send anyway (lead)
            </button>
          ) : (
            <div className="grid gap-2 rounded-[14px] border border-line bg-bg/60 p-3">
              <p className="text-[13px] text-muted">Sending it with {c.blocking.map((g) => GATE_LABEL[g].toLowerCase()).join(" and ")}. Why can it go anyway? It&apos;s kept with the brief.</p>
              <textarea value={reason} onChange={(e) => setReason(e.target.value)} rows={2} placeholder="e.g. The client confirmed the seat on today's call; footage lands Monday" className="w-full rounded-[12px] border border-line bg-surface px-3.5 py-2.5 text-[16px] outline-none focus:border-brand/60 md:text-[14px]" />
              <div className="flex gap-2">
                <button type="button" onClick={override} disabled={reason.trim().length < 8 || Boolean(busy)} className="min-h-11 rounded-full bg-fg px-4 text-[13px] font-medium text-bg disabled:opacity-50">
                  {busy === "override" ? "Saving…" : "Send it on"}
                </button>
                <button type="button" onClick={() => setOverriding(false)} className="min-h-11 rounded-full px-4 text-[13px] text-muted hover:text-fg">
                  Cancel
                </button>
              </div>
            </div>
          )}
        </div>
      )}

      {/* The revise chat */}
      {!demo && ok?.canEdit && (
        <div className="grid gap-2.5 border-t border-line pt-4">
          <p className="text-[11px] font-semibold uppercase tracking-[0.16em] text-faint">Revise{ok.copyOnly ? " the copy lines" : ""}</p>
          {(turns.length > 0 || log.length > 0) && (
            <div ref={listRef} className="grid max-h-[340px] gap-2 overflow-y-auto overscroll-contain pr-1">
              {turns.length === 0 &&
                log
                  .filter((l) => l.kind === "correction")
                  .slice(0, 5)
                  .reverse()
                  .map((l) => (
                    <div key={l.id} className="grid gap-1 rounded-[14px] bg-bg/60 px-3.5 py-2.5 text-[13px]">
                      <p className="text-faint">
                        {l.by} · {new Date(l.at).toLocaleDateString("en-US", { month: "short", day: "numeric" })}
                        {l.undone ? " · undone" : ""}
                      </p>
                      <p className="text-fg/90">{l.instruction}</p>
                    </div>
                  ))}
              {turns.map((t, i) => (
                <div key={i} className={`grid gap-1.5 ${t.role === "user" ? "justify-items-end" : ""}`}>
                  <p className={`max-w-[92%] rounded-[16px] px-3.5 py-2.5 text-[14px] leading-snug ${t.role === "user" ? "bg-fg text-bg" : "bg-bg/70 text-fg"}`}>{t.text}</p>
                  {t.diff && t.diff.length > 0 && (
                    <details className={`max-w-[92%] rounded-[14px] border border-line px-3.5 py-2 text-[13px] ${t.undone ? "opacity-60" : ""}`}>
                      <summary className="flex min-h-9 cursor-pointer items-center justify-between gap-2 text-muted">
                        <span>Changed {t.diff.map((d) => d.label).join(", ")}{t.undone ? " · undone" : ""}</span>
                        {t.correctionId && !t.undone && (
                          <button type="button" onClick={(e) => (e.preventDefault(), undo(i, t.correctionId!))} disabled={Boolean(busy)} className="min-h-9 rounded-full border border-line px-3 text-[12.5px] text-fg hover:border-faint disabled:opacity-60">
                            {busy === `undo-${i}` ? "Undoing…" : "Undo"}
                          </button>
                        )}
                      </summary>
                      <div className="grid gap-2 pb-1 pt-2">
                        {t.diff.map((d) => (
                          <div key={d.field} className="grid gap-0.5">
                            <span className="text-[11px] font-semibold uppercase tracking-[0.12em] text-faint">{d.label}</span>
                            {d.before && <span className="whitespace-pre-wrap text-faint line-through decoration-faint/60">{d.before}</span>}
                            {d.after && <span className="whitespace-pre-wrap text-fg">{d.after}</span>}
                          </div>
                        ))}
                      </div>
                    </details>
                  )}
                </div>
              ))}
              {busy === "revise" && <p className="text-[13px] text-faint">Changing it…</p>}
            </div>
          )}
          <form
            onSubmit={(e) => {
              e.preventDefault();
              void send(say);
            }}
            className="flex items-end gap-2"
          >
            <textarea
              value={say}
              onChange={(e) => setSay(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === "Enter" && !e.shiftKey) {
                  e.preventDefault();
                  void send(say);
                }
              }}
              rows={1}
              placeholder={ok.copyOnly ? "Tell me what to change in the hook or key message" : "Tell me what to change"}
              aria-label="Tell me what to change"
              className="max-h-40 min-h-11 min-w-0 flex-1 resize-none rounded-[16px] border border-line bg-bg/60 px-3.5 py-2.5 text-[16px] leading-snug outline-none placeholder:text-faint focus:border-brand/60 md:text-[14px]"
            />
            <button type="submit" disabled={!say.trim() || Boolean(busy)} className="min-h-11 shrink-0 rounded-full bg-brand px-4 text-[14px] font-medium text-white disabled:opacity-50">
              Send
            </button>
          </form>
          <p className="text-[12px] text-faint">It knows the client: Brand Bible, past performance, what&apos;s on Drive. Every correction is kept and teaches the brief writer.</p>
        </div>
      )}

      {/* The stamp */}
      {!demo && ok?.canEdit && !ok.copyOnly && !c?.stamp && (
        <div className="flex flex-wrap items-center justify-between gap-2 border-t border-line pt-3">
          <p className="text-[12.5px] text-muted">Looked it over? Stamp it so the maker knows a person checked it.</p>
          <button type="button" onClick={review} disabled={Boolean(busy)} className="min-h-11 rounded-full border border-ok/50 px-4 text-[13px] font-medium text-ok hover:bg-ok-soft disabled:opacity-60 md:min-h-9">
            {busy === "review" ? "Saving…" : "Mark reviewed"}
          </button>
        </div>
      )}
      {error && <p className="text-[13px] text-bad">{error}</p>}
      {res && !res.ok && <p className="text-[13px] text-faint">{res.error}</p>}
    </section>
  );
}
